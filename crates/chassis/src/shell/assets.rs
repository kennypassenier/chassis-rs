#[cfg(feature = "assets")]
pub const WEBAPP_KP_ASSETS: &[(&str, &str, &[u8])] = WEBAPP_TABLE;

/// The one copy of the bytes behind `WEBAPP_KP_ASSETS` (see `CORE_TABLE`).
#[cfg(feature = "assets")]
static WEBAPP_TABLE: &[(&str, &str, &[u8])] =
    include!(concat!(env!("OUT_DIR"), "/assets_webapp.rs"));

/// Every asset this build serves: the kit's own set, plus the full
/// kp-themes module set (every build with `assets`).
pub fn all_assets() -> impl Iterator<Item = &'static (&'static str, &'static str, &'static [u8])> {
    CORE_TABLE.iter().chain(WEBAPP_TABLE.iter())
}

/// The vendored manifest, for the gate test and `--print-config`'s
/// "built with kp-themes x.y.z" line.
pub const KP_THEMES_MANIFEST: &str = include_str!("../../static/kp/KP_THEMES.sha256");

/// FNV-1a over every asset, as the `?v=` cache-buster: any byte changed in
/// any file changes every URL, which is what makes a one-year
/// `immutable` cache safe.
pub fn asset_version() -> &'static str {
    static VERSION: std::sync::OnceLock<String> = std::sync::OnceLock::new();
    VERSION.get_or_init(|| fnv_version(CORE_TABLE.iter().map(|(name, _, body)| (*name, *body))))
}

/// FNV-1a over `(name, body)` pairs, 16 hex chars.
pub fn fnv_version<'a>(parts: impl Iterator<Item = (&'a str, &'a [u8])>) -> String {
    let mut h: u64 = 0xcbf2_9ce4_8422_2325;
    for (name, body) in parts {
        for b in name.bytes().chain(body.iter().copied()) {
            h ^= b as u64;
            h = h.wrapping_mul(0x0000_0100_0000_01b3);
        }
    }
    format!("{h:016x}")
}

/// The path segment that versions a whole subtree of `/static/`
/// (fix-warm-1): `/static/v-<asset_version>/chassis.js` is
/// `/static/chassis.js`, cached for a year, and so is every module it reaches
/// by a relative import. A `?v=` versions one URL only; the kit's own modules
/// import each other relatively, so on a warm load each of them was asked
/// again (110-135 revalidations per kit page, measured on 4.7.0).
pub(crate) const VERSIONED_SEGMENT: &str = "v-";

/// `/static/v-<asset_version>/` — prefix of the versioned subtree.
pub(crate) fn versioned_root() -> &'static str {
    static ROOT: std::sync::OnceLock<String> = std::sync::OnceLock::new();
    ROOT.get_or_init(|| format!("/static/{VERSIONED_SEGMENT}{}/", asset_version()))
}

/// A `/static/…` URL moved under [`versioned_root`]; any other URL as it is.
pub(crate) fn versioned_static(url: &str) -> String {
    match url.strip_prefix("/static/") {
        Some(rest) => format!("{}{rest}", versioned_root()),
        None => url.to_string(),
    }
}

/// `name` without a leading `v-<version>/`, and whether that version is this
/// build's (only then may the answer be cached for good: an old page's URL
/// gets today's file, which must not stick).
fn strip_version(name: &str) -> (&str, bool) {
    let Some((segment, rest)) = name
        .strip_prefix(VERSIONED_SEGMENT)
        .and_then(|r| r.split_once('/'))
    else {
        return (name, false);
    };
    let current = format!("{VERSIONED_SEGMENT}{segment}/") == versioned_root()["/static/".len()..];
    (rest, current)
}

/// `GET /static/{name}`.
pub async fn serve(Path(name): Path<String>, RawQuery(query): RawQuery) -> Response {
    serve_conditional(Path(name), RawQuery(query), HeaderMap::new()).await
}

/// `GET /static/{name}` with revalidation (fix-13). The layout links every
/// asset with `?v=<content hash>`, so those URLs may be cached for a year.
/// A URL without it — a font reached from inside fonts.css, a project's app
/// importing `/static/kp/js/…`, an entry of the split bundle — gets `no-cache` and a strong `ETag`, and an
/// unchanged file answers 304: a kp-themes bump reaches an open tab at its
/// next reload, where the old one-day cache kept the old files for a day.
pub async fn serve_conditional(
    Path(name): Path<String>,
    RawQuery(query): RawQuery,
    headers: HeaderMap,
) -> Response {
    // A chunk of the split module folder is named after its content hash, so
    // its URL never changes meaning: cached for a year without a `?v=`.
    let (name, current) = strip_version(&name);
    let versioned =
        current || query.as_deref().is_some_and(|q| q.contains("v=")) || is_hashed_chunk(name);
    let Some((_, ct, body)) = all_assets().find(|(n, _, _)| *n == name) else {
        return (StatusCode::NOT_FOUND, "no such asset").into_response();
    };
    if versioned {
        return (
            [
                (header::CONTENT_TYPE, *ct),
                (header::CACHE_CONTROL, "public, max-age=31536000, immutable"),
            ],
            *body,
        )
            .into_response();
    }
    let etag = format!("\"{}\"", fnv_version(std::iter::once(("", *body))));
    let unchanged = etag_matches(&headers, &etag);
    let mut res = if unchanged {
        StatusCode::NOT_MODIFIED.into_response()
    } else {
        ([(header::CONTENT_TYPE, *ct)], *body).into_response()
    };
    let h = res.headers_mut();
    h.insert(header::CACHE_CONTROL, HeaderValue::from_static("no-cache"));
    if let Ok(v) = HeaderValue::from_str(&etag) {
        h.insert(header::ETAG, v);
    }
    res
}

/// `kp/dist/js/chunk-<hash>.js`: the content-hashed chunks of the split
/// bundle. The entries (`auto.js`, `core.js`, ...) and the maps are not.
pub(crate) fn is_hashed_chunk(name: &str) -> bool {
    name.strip_prefix("kp/dist/js/chunk-")
        .is_some_and(|rest| rest.ends_with(".js") && !rest.contains('/'))
}

/// Whether the request's `If-None-Match` names `etag` (the strong form the
/// handler computed), in its strong or its weak (`W/`) spelling: a gzip answer
/// carries the weak form (see `compress`).
pub(crate) fn etag_matches(headers: &HeaderMap, etag: &str) -> bool {
    headers
        .get(header::IF_NONE_MATCH)
        .and_then(|v| v.to_str().ok())
        .is_some_and(|v| {
            v.split(',')
                .any(|t| t.trim().trim_start_matches("W/") == etag)
        })
}

