/// name → (content type, bytes). Generated by `build.rs` from `static/`
/// (own files, kp css/fonts, the core kp modules); no path joining at
/// request time (kyu's traversal-proof shape).
///
/// A `const`, as published (the recorded API contract keeps its shape), but
/// the kit never reads it: a const is inlined at every use, and each use
/// carried its own copy of every embedded byte (the binary held each asset
/// twice, measured 2026-11-02 with the source-maps feature: +44 MB for 22 MB
/// of maps). The kit reads the private static `CORE_TABLE`, which holds the
/// bytes once. A caller outside the kit that uses this const pays that copy.
pub const ASSETS: &[(&str, &str, &[u8])] = CORE_TABLE;

/// The one copy of the bytes behind `ASSETS`: the public name stays a `const`
/// (its published shape), and the const only points here.
static CORE_TABLE: &[(&str, &str, &[u8])] = include!(concat!(env!("OUT_DIR"), "/assets_core.rs"));

/// The checkout `build.rs` listed `static/` in. A shared target directory can
/// hand this crate the build-script output of another checkout (a second
/// worktree), whose file list may differ; the build stops instead of
/// serving that list.
const GENERATED_FOR: &str = include!(concat!(env!("OUT_DIR"), "/generated_for.rs"));
const _: () = assert!(
    same(GENERATED_FOR, env!("CARGO_MANIFEST_DIR")),
    "the asset tables were generated for another checkout of chassis; run `touch crates/chassis/build.rs` and build again"
);

/// `a == b` for strings, usable in a `const` assertion.
const fn same(a: &str, b: &str) -> bool {
    let (a, b) = (a.as_bytes(), b.as_bytes());
    if a.len() != b.len() {
        return false;
    }
    let mut i = 0;
    while i < a.len() {
        if a[i] != b[i] {
            return false;
        }
        i += 1;
    }
    true
}

